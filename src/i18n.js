// ---------------------------------------------------------------------------
// Module-level lang state with pub/sub so ALL useI18n() callers re-render
// together when the language is toggled from any component.
// ---------------------------------------------------------------------------

let _lang = localStorage.getItem('leen_lang') || 'ar';
const _listeners = new Set();

function setGlobalLang(nl) {
  _lang = nl;
  localStorage.setItem('leen_lang', nl);
  document.documentElement.dir  = nl === 'ar' ? 'rtl' : 'ltr';
  document.documentElement.lang = nl;
  _listeners.forEach((fn) => fn(nl));
}

export function useI18n() {
  const [lang, setLang] = useState(_lang);

  useEffect(() => {
    _listeners.add(setLang);
    return () => _listeners.delete(setLang);
  }, []);

  const t = (key) =>
    key.split('.').reduce((obj, k) => obj?.[k], translations[lang]) || key;

  const toggleLang = () => setGlobalLang(lang === 'ar' ? 'en' : 'ar');

  return { t, lang, toggleLang };
}
